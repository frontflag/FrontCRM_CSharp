const seen = new Set()
const out = []
for (const row of list) {
  if (seen.has(row[1])) continue
  seen.add(row[1])
  out.push(row)
}

const pri = new Map(priority.map((c, i) => [c, i]))
out.sort((a, b) => {
  const pa = pri.has(a[1]) ? pri.get(a[1]) : 9999
  const pb = pri.has(b[1]) ? pri.get(b[1]) : 9999
  if (pa !== pb) return pa - pb
  return a[0].localeCompare(b[0], 'zh-CN')
})

const lines = out.map((row) => {
  const extras = row.slice(3).map((s) => JSON.stringify(s)).join(', ')
  const tail = extras ? `, ${extras}` : ''
  return `  [${JSON.stringify(row[0])}, ${JSON.stringify(row[1])}, ${JSON.stringify(row[2])}${tail}],`
})

